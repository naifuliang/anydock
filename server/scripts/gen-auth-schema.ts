// Generates migrations/0001_auth.sql from the Better Auth config, using an in-memory SQLite DB.
// Run: npm run gen:auth-schema
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.ts";

const options = authOptions(
  { BETTER_AUTH_URL: "http://localhost", BETTER_AUTH_SECRET: "schema-only-secret-0123456789abcdef" },
  new DatabaseSync(":memory:"),
);
const { compileMigrations } = await getMigrations(options);
const sql = await compileMigrations();
writeFileSync(fileURLToPath(import.meta.resolve("../migrations/0001_auth.sql")), `-- Generated by scripts/gen-auth-schema.ts. Do not edit by hand.\n${sql}\n`);
console.log(sql);
